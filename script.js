function applyTheme(theme) {
  root.classList.toggle('dark', theme === 'dark');
  localStorage.setItem('rt_theme', theme);
  state.theme = theme;
}

function applyLang(lang) {
  const map = translations[lang];
  document.documentElement.lang = lang;
  document.querySelectorAll('[data-i18n]').forEach((node) => {
    const key = node.getAttribute('data-i18n');
    if (map[key]) node.textContent = map[key];
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach((node) => {
    const key = node.getAttribute('data-i18n-placeholder');
    if (map[key]) node.setAttribute('placeholder', map[key]);
  });
  langToggle.textContent = lang === 'en' ? 'ES' : 'EN';
  localStorage.setItem('rt_lang', lang);
  state.lang = lang;
}

applyTheme(state.theme);
applyLang(state.lang);

langToggle.addEventListener('click', () => applyLang(state.lang === 'en' ? 'es' : 'en'));
themeToggle.addEventListener('click', () => applyTheme(state.theme === 'dark' ? 'light' : 'dark'));

